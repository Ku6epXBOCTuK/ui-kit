// NOTE: Compiles the hct()-authored theme into plain hex, so no consumer
// needs a PostCSS plugin. Run after editing tokens/tool.src.css.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import postcssHct from "./postcss-hct.mjs";

const source = new URL("../tokens/tool.src.css", import.meta.url);
const target = new URL("../tokens/tool.css", import.meta.url);

const header = `/* NOTE: Generated by scripts/build-themes.mjs - edit tokens/tool.src.css. */\n`;

const input = await readFile(source, "utf8");
const { css } = await postcss([postcssHct]).process(input, {
	from: fileURLToPath(source),
});

const body = css.replace(/\/\*[\s\S]*?\*\//g, "");
if (/\bhct\(/.test(body)) {
	throw new Error(
		"Unresolved hct() left in the output, check the authoring source",
	);
}

await writeFile(target, header + body.trim() + "\n", "utf8");

const tokens = new Set(body.match(/--ui-[\w-]+(?=\s*:)/g) ?? []);
console.log(
	`tokens/tool.css written: ${tokens.size} tokens, ${Buffer.byteLength(body)} bytes`,
);
